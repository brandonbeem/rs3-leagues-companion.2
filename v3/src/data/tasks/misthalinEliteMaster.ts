const requirements = (partial: Partial<TaskRequirements> = {}): TaskRequirements => ({
  skills: partial.skills ?? [],
  items: partial.items ?? [],
  quests: partial.quests ?? [],
  unlocks: partial.unlocks ?? [],
  completedTaskIds: partial.completedTaskIds ?? [],
});

type LateTaskInput = {
  tier: Extract<TaskTier, 'elite' | 'master'>;
  slug: string;
  name: string;
  information: string;
  locality: string;
  locationId: TaskDefinition['locationId'];
  category: TaskCategory;
  requirements?: Partial<TaskRequirements>;
  estimatedSeconds?: number | null;
  completionRate?: number;
  manual?: boolean;
  review?: TaskDefinition['reviewStatus'];
  notes?: string[];
};

const lateTask = (input: LateTaskInput): TaskDefinition => {
  const manual = input.manual ?? true;
  return {
    id: ids.task(`catalyst-misthalin-${input.tier}-${input.slug}`),
    name: input.name,
    description: input.information,
    information: input.information,
    category: input.category,
    tier: input.tier,
    priority: manual ? 'Long Grind' : 'Late',
    points: input.tier === 'elite' ? 200 : 400,
    locality: input.locality,
    regionId: MISHTHALIN_ID,
    locationId: input.locationId,
    requirements: requirements(input.requirements),
    recommendedItemIds: [],
    acquisitionSteps: [{
      type: 'perform-action',
      label: input.information,
      locationId: input.locationId ?? undefined,
      notes: manual ? 'Long-term player-controlled goal; excluded from automatic task routes.' : undefined,
    }],
    nearbyTaskIds: [],
    estimatedSeconds: input.estimatedSeconds ?? null,
    routePolicy: manual ? 'manual-only' : 'normal',
    reviewStatus: input.review ?? 'verified',
    sources: [catalystTasks],
    completionRate: input.completionRate,
    notes: input.notes,
  };
};

